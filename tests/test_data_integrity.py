"""Safety tests over the REAL committed data. Run before every deployment (CI + update workflow)."""
import json
import os
import re
import unittest
from tests.helpers import *  # noqa
from evidence import publish
from evidence.ledger import Ledger
from evidence.normalize import doi_syntax_ok, identity_keys, year_of

DATA = os.path.join(ROOT, "data")
ARTICLES = os.path.join(DATA, "articles.json")


def iter_items(out):
    for c in out["categories"]:
        for a in c["articles"]:
            yield f"categories/{c['id']}", a
    for k in ("trending", "foamed", "bottom_line", "guidelines", "ksa", "this_week", "preprints", "trials"):
        for a in (out.get(k) or {}).get("articles", []):
            yield k, a


@unittest.skipUnless(os.path.exists(ARTICLES), "no articles.json")
class TestCommittedData(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.out = json.load(open(ARTICLES, encoding="utf-8"))
        cls.items = list(iter_items(cls.out))
        cls.gated = any(a.get("evidence") for _, a in cls.items)

    def test_doi_and_pmid_syntax(self):
        for sec, a in self.items:
            if a.get("doi"):
                self.assertTrue(doi_syntax_ok(a["doi"]), f"{sec}: {a['doi']}")
            if a.get("pmid"):
                self.assertRegex(str(a["pmid"]), r"^\d{1,9}$")

    def test_no_duplicate_publications_within_a_section(self):
        for sec in {s for s, _ in self.items}:
            keys = [identity_keys(a)[0] for s, a in self.items if s == sec and identity_keys(a)]
            self.assertEqual(len(keys), len(set(keys)), f"duplicates in {sec}")

    def test_publication_dates_are_plausible(self):
        for sec, a in self.items:
            y = year_of(a.get("pubdate"))
            self.assertTrue(y is None or 1990 <= y <= 2027, f"{sec}: {a.get('title')} -> {a.get('pubdate')}")

    def test_trial_identifiers_are_well_formed_and_consistent(self):
        for sec, a in self.items:
            if a.get("nct_id"):
                self.assertRegex(a["nct_id"], r"^NCT\d{8}$")
                self.assertIn(a["nct_id"], a.get("url", ""), "NCT id must match the linked registry URL")

    def test_required_fields_present(self):
        for sec, a in self.items:
            self.assertTrue(a.get("title"), sec)
            if sec.startswith("categories/") or sec in ("guidelines", "ksa", "trending"):
                self.assertTrue(a.get("pmid") or a.get("doi"), f"{sec}: {a.get('title')}")

    def test_critical_safety_gate_on_committed_data(self):
        if not self.gated:
            self.skipTest("articles.json predates the evidence system (regenerated by the next pipeline run)")
        led = Ledger(DATA)
        crit = [f for f in publish.safety_check(self.out, led) if f["severity"] == "critical"]
        self.assertEqual(crit, [], crit[:5])

    def test_audit_log_chain_intact(self):
        self.assertTrue(Ledger(DATA).audit.verify_chain()[0])

    def test_ai_text_only_with_validated_status(self):
        if not self.gated:
            self.skipTest("pre-evidence data")
        for sec, a in self.items:
            if a.get("ai_summary") or a.get("ai_appraisal"):
                self.assertIn(a["evidence"]["ai_status"], ("auto_validated", "editor_approved"), f"{sec}: {a['title']}")
            self.assertNotIn("ai_rounds_takeaway" if a["evidence"]["ai_status"] != "editor_approved" else "-", a)

    def test_retracted_items_carry_no_ai_and_are_not_promoted(self):
        if not self.gated:
            self.skipTest("pre-evidence data")
        for sec, a in self.items:
            if a["evidence"]["retraction_status"] == "retracted":
                self.assertFalse(a.get("ai_summary") or a.get("ai_appraisal"))
                self.assertNotIn(sec.split("/")[0], publish.PROMOTION_SECTIONS)


if __name__ == "__main__":
    unittest.main()
